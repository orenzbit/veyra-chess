-- Veyra Chess server data schema.
-- Run this in Supabase SQL editor before enabling persistent telemetry/admin bot overrides.

create table if not exists public.telemetry_events (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  event_type text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists telemetry_events_created_at_idx on public.telemetry_events(created_at desc);
create index if not exists telemetry_events_type_idx on public.telemetry_events(event_type);
create index if not exists telemetry_events_visitor_idx on public.telemetry_events(visitor_id);


create table if not exists public.adaptive_signals (
  id bigint generated by default as identity primary key,
  visitor_id text not null,
  principle text not null,
  phase text not null default 'unknown',
  severity integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists adaptive_signals_principle_idx on public.adaptive_signals(principle);
create index if not exists adaptive_signals_created_at_idx on public.adaptive_signals(created_at desc);

create table if not exists public.bot_overrides (
  slug text primary key,
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

alter table public.telemetry_events enable row level security;
alter table public.adaptive_signals enable row level security;
alter table public.bot_overrides enable row level security;

-- No public/browser policy is intentionally granted here.
