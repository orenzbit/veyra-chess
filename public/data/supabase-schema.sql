-- Private-beta manual access approval codes. No client-side or public policies are granted.
create table if not exists public.signup_access_codes (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  status text not null default 'pending',
  code_hash text not null,
  expires_at timestamptz not null,
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  approved_by text,
  rejected_at timestamptz,
  rejected_by text,
  used_at timestamptz,
  revoked_at timestamptz,
  attempts integer not null default 0,
  requested_ip text,
  signup_completed boolean not null default false
);
alter table public.signup_access_codes add column if not exists status text not null default 'pending';
alter table public.signup_access_codes add column if not exists approved_at timestamptz;
alter table public.signup_access_codes add column if not exists approved_by text;
alter table public.signup_access_codes add column if not exists rejected_at timestamptz;
alter table public.signup_access_codes add column if not exists rejected_by text;
update public.signup_access_codes set status='completed' where signup_completed = true;
update public.signup_access_codes set status='code_verified' where signup_completed = false and used_at is not null and revoked_at is null;
update public.signup_access_codes set status='revoked' where signup_completed = false and revoked_at is not null;
create index if not exists signup_access_codes_status_created_idx on public.signup_access_codes(status, created_at desc);
create index if not exists signup_access_codes_email_created_idx on public.signup_access_codes(email, created_at desc);
create index if not exists signup_access_codes_ip_created_idx on public.signup_access_codes(requested_ip, created_at desc);
alter table public.signup_access_codes enable row level security;


