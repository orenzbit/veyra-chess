// Generates netlify/functions/lib/wasm-engine.gen.mjs: the browser UMD engine wrapper
// (public/vendor/wasm-engine.js) as an ES module for Node.
// The UMD file only sets globalThis.WasmEngine when loaded as an ES module, so the entry
// imports it for its side effect and re-exports the global.
// Usage: node scripts/build-engine-node.mjs [--check]
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(root, 'netlify/functions/lib/wasm-engine.gen.mjs');
const check = process.argv.includes('--check');
const result = await build({
  stdin: {
    contents: "import './wasm-engine.js';\nexport default globalThis.WasmEngine;\n",
    resolveDir: join(root, 'public/vendor'),
    sourcefile: 'engine-entry.mjs',
  },
  bundle: true, format: 'esm', platform: 'node', target: 'node20', write: false, legalComments: 'none', logLevel: 'error',
});
const code = '// GENERATED by scripts/build-engine-node.mjs from public/vendor/wasm-engine.js. Do not edit.\n' + result.outputFiles[0].text;
if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== code) { console.error('STALE: run node scripts/build-engine-node.mjs'); process.exit(1); }
  console.log('PASS: Node engine wrapper is up to date');
} else {
  await writeFile(OUT, code);
  console.log('built', OUT, code.length, 'bytes');
}
